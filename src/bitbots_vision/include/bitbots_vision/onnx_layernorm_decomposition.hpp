#pragma once

#include <string>

/// Rewrites ONNX `LayerNormalization` nodes into primitive ops.
///
/// `LayerNormalization` became a standard ONNX op in opset 17, and PyTorch
/// emits it as a single node when exporting at that opset. TensorRT only
/// gained a native importer for it in TensorRT 8.6, so older TensorRT
/// versions (e.g. TensorRT 8.5 on JetPack 5) fail to parse such models.
/// Decomposing every such node into ReduceMean / Sub / Mul / Add / Sqrt / Div
/// beforehand gives a numerically equivalent graph that every TensorRT 8.x
/// parser understands.
///
/// The rewrite operates directly on the protobuf wire format of the
/// serialized `onnx.ModelProto`, so no ONNX / protobuf library is required.
///
/// Like the ONNX op with its default `stash_type`, the decomposition computes
/// in float32: inputs of other element types (e.g. float16) are cast to
/// float32 and the result is cast back.
///
/// Only nodes of the top-level graph are rewritten; nodes inside subgraphs
/// (If / Loop bodies) and nodes that cannot be decomposed safely (positive
/// `axis`, used auxiliary `Mean` / `InvStdDev` outputs, or an element type
/// that cannot be determined from initializers, value infos, Cast or Constant
/// nodes) are kept untouched.
namespace bitbots_vision::onnx_rewrite {

/// Substring contained in the name of every node generated by the
/// decomposition, so callers can identify these layers after parsing (e.g.
/// to keep them in FP32 when building a reduced-precision TensorRT engine).
inline constexpr const char* kDecomposedNodeTag = "/ln_decomposed/";

struct LayerNormDecompositionResult {
  /// Serialized `onnx.ModelProto` with all supported LayerNormalization nodes
  /// decomposed. Identical to the input if nothing was replaced.
  std::string model;
  /// Number of LayerNormalization nodes that were decomposed.
  int num_decomposed{0};
  /// Number of LayerNormalization nodes that were left as-is because they
  /// could not be decomposed safely.
  int num_skipped{0};
};

/// Decompose all supported LayerNormalization nodes of the given serialized
/// ONNX model. Throws std::runtime_error if the model cannot be parsed.
LayerNormDecompositionResult decompose_layer_normalization(const std::string& serialized_model);

}  // namespace bitbots_vision::onnx_rewrite
